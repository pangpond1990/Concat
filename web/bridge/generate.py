#!/usr/bin/env python3
"""Generate typed transport from the upstream Slint public interface.
No hand-maintained duplicate editor schema or reimplemented edit commands.
"""
from pathlib import Path
import re
import json

ROOT=Path(__file__).resolve().parents[2]
UI=ROOT/'src/crates/concat/ui'

def clean(s):
    return re.sub(r'/\*.*?\*/|//[^\n]*', '', s, flags=re.S)

def block(s, start):
    depth=1; i=start
    while depth:
        if s[i]=='{': depth+=1
        elif s[i]=='}': depth-=1
        i+=1
    return s[start:i-1]

def ident(s):
    s=s.replace('-','_')
    return 'r#'+s if s in ['type','ref','move','match','loop','in','as','use','mod','self','where','box'] else s

def variant(s): return ''.join(x[:1].upper()+x[1:] for x in s.split('-'))

def typ(s):
    s=s.strip()
    if s.startswith('['): return f'slint::ModelRc<{typ(s[1:-1])}>'
    return {'string':'slint::SharedString','int':'i32','float':'f32','bool':'bool','length':'f32','physical-length':'f32','duration':'i64','angle':'f32','color':'slint::Color','brush':'slint::Brush','image':'slint::Image'}.get(s,s)

structs={}; enums={}; globals={}; source={}
for f in UI.rglob('*.slint'):
    s=clean(f.read_text())
    for m in re.finditer(r'export (struct|enum|global|component) (\w+)(?: inherits \w+)?\s*\{',s):
        kind,name=m[1],m[2]; body=block(s,m.end())
        source[name]=f.relative_to(ROOT).as_posix()
        if kind=='struct':
            structs[name]=re.findall(r'([\w-]+)\s*:\s*([^,]+),?',body)
        elif kind=='enum': enums[name]=[x.strip() for x in body.split(',') if x.strip()]
        elif kind=='global' or name=='App':
            # Read only declarations directly inside the exported block, not children.
            flat=[]; depth=0
            for line in body.splitlines():
                if depth==0: flat.append(line)
                depth+=line.count('{')-line.count('}')
            body='\n'.join(flat)
            props=re.findall(r'\b(in|in-out|out) property\s*<([^>]+)>\s*([\w-]+)',body)
            callbacks=[]
            for c in re.finditer(r'\b(pure\s+)?callback\s+([\w-]+)\((.*?)\)\s*(?:->\s*([\w-]+))?\s*;',body,re.S):
                args=[]
                for arg in c[3].split(','):
                    if arg.strip():
                        n,t=arg.strip().split(':'); args.append((n.strip(),t.strip()))
                callbacks.append(dict(name=c[2],args=args,returns=c[4],pure=bool(c[1])))
            globals[name]=dict(props=props,callbacks=callbacks)
# App exports determine which globals the original Rust host can reach.
app=clean((UI/'app.slint').read_text())
exports=re.search(r'export\s*\{(.*?)\}',app,re.S)[1]
selected=['App']+[n for n in re.findall(r'\w+',exports) if n in globals]
# Pure globals execute locally; their computed properties are not state.
selected=[n for n in selected if n not in ['Fmt','Curves','Payload','Focus']]
needed=set()
def need(t):
    t=t.strip()
    if t.startswith('['): return need(t[1:-1])
    if t in needed: return
    if t in structs:
        needed.add(t)
        for _,field in structs[t]: need(field)
    elif t in enums: needed.add(t)
for n in selected:
    for direction,t,k in globals[n]['props']:
        if direction!='out': need(t)
    for c in globals[n]['callbacks']:
        if not c['pure']:
            for _,t in c['args']: need(t)

lines=['// Generated by web/bridge/generate.py from the actual upstream Slint interfaces.',
       '// SPDX-License-Identifier: AGPL-3.0-or-later',
       'use crate::ui::*;','use slint::ComponentHandle;', 'use super::wire::{Wire, Result};', 'use serde_json::{Value, json};']
for n in sorted(needed):
    if n in structs:
        fields=structs[n]
        lines+= [f'impl Wire for {n} {{', 'fn wire(&self) -> Value { let mut map=serde_json::Map::new();']
        for k,t in fields: lines+=[f'map.insert("{k}".into(), self.{ident(k)}.wire());']
        lines+=['Value::Object(map) }','fn update(&mut self, value: &Value) -> Result<()> {']
        for k,t in fields: lines+=[f'if let Some(v)=value.get("{k}") {{ self.{ident(k)}.update(v)?; }}']
        lines+=['Ok(()) }}']
    else:
        lines+=[f'impl Wire for {n} {{','fn wire(&self) -> Value { json!(match self {']
        lines += [f'Self::{variant(v)} => "{v}",' for v in enums[n]]
        lines+=['_ => "unknown", }) }','fn update(&mut self,value: &Value)->Result<()> { *self=match value.as_str() {']
        lines += [f'Some("{v}") => Self::{variant(v)},' for v in enums[n]]
        lines+=['other => return Err(format!("invalid enum: {other:?}")), }; Ok(()) }}']

lines+=['#[cfg(not(target_arch="wasm32"))]', 'pub fn snapshot(app: &App) -> Value { let mut map=serde_json::Map::new();']
for n in selected:
    obj='app' if n=='App' else f'app.global::<{n}>()'
    for d,t,k in globals[n]['props']:
        if d!='out': lines+=[f'map.insert("{n}.{k}".into(), {obj}.get_{ident(k)}().wire());']
lines+=['Value::Object(map) }','#[cfg(target_arch="wasm32")]', 'pub fn apply(app: &App, state: &Value) -> Result<()> {']
for n in selected:
    obj='app' if n=='App' else f'app.global::<{n}>()'
    for d,t,k in globals[n]['props']:
        if d!='out':
            lines+=[f'if let Some(v)=state.get("{n}.{k}") {{ let mut current={obj}.get_{ident(k)}(); current.update(v)?; {obj}.set_{ident(k)}(current); }}']
lines+=['Ok(()) }','#[cfg(not(target_arch="wasm32"))]', 'pub fn invoke(app: &App, name: &str, args: &[Value]) -> Result<Value> { match name {']
for n in selected:
    obj='app' if n=='App' else f'app.global::<{n}>()'
    for c in globals[n]['callbacks']:
        if c['pure']: continue
        lines+=[f'"{n}.{c["name"]}" => {{']
        for i,(_,t) in enumerate(c['args']):
            lines+=[f'let mut a{i}: {typ(t)}=Default::default(); a{i}.update(args.get({i}).ok_or("missing argument")?)?;']
        call=f'{obj}.invoke_{ident(c["name"])}('+','.join(f'a{i}' for i in range(len(c['args'])))+')'
        lines+=[f'Ok({call}.wire())' if c['returns'] else f'{call}; Ok(Value::Null)', '},']
lines+=['_ => Err(format!("unknown UI callback: {name}")), }}', '#[cfg(target_arch="wasm32")]', 'pub fn bind(app: &App) {']
for n in selected:
    obj='app' if n=='App' else f'app.global::<{n}>()'
    for c in globals[n]['callbacks']:
        if c['pure'] or c['returns']: continue
        args=','.join(f'a{i}' for i in range(len(c['args'])))
        values=','.join(f'a{i}.wire()' for i in range(len(c['args'])))
        lines+=[f'{obj}.on_{ident(c["name"])}(move |{args}| super::emit("{n}.{c["name"]}", vec![{values}]));']
lines+=['}']
(ROOT/'web/bridge/generated.rs').write_text('\n'.join(lines)+'\n')
(ROOT/'web/bridge/schema.json').write_text(json.dumps({n:globals[n] for n in selected},indent=2)+'\n')
print(f'{len(selected)} globals, {len(needed)} value types, '+str(sum(len(globals[n]['callbacks']) for n in selected))+' callbacks')
